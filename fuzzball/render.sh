#!/usr/bin/env bash
# Fill the Fuzzfile templates with this cluster's values. Defaults = CIQ fb-hack cluster, team9.
#
#   bash fuzzball/render.sh                       # all defaults below
#   NCCL_IFACE=enP7s7 bash fuzzball/render.sh     # override any value with VAR=value
#
# Variables: IMAGE VOLUME PROVISIONER PORT NCCL_IFACE REPO_DIR MODEL_DIR CONFIG_1N CONFIG_2N
#            GIT_URL GIT_BRANCH COLLECT_TAG (not saved; a fresh timestamp each render)
# Output: fuzzball/rendered/*.fz and fuzzball/cluster.env (sourced by node_entry.sh on every node).
#
# Values are saved to fuzzball/render.env, so later you only pass what changes, e.g.:
#   CONFIG_2N=configs/replicate-2n-r2.yaml bash fuzzball/render.sh
set -euo pipefail
cd "$(dirname "$0")"
if [[ -f render.env ]]; then  # saved values; anything set on the command line wins
  while IFS='=' read -r k v; do
    [[ -z "$k" || "$k" == \#* ]] && continue
    [[ -z "${!k:-}" ]] && export "$k=$v"
  done < render.env
fi
IMAGE=${IMAGE:-docker://nvcr.io/nvidia/nemo-automodel:26.10.00}
VOLUME=${VOLUME:-models}
PORT=${PORT:-29501}          # CIQ example opens 13345 and 29501 between nodes
PROVISIONER=${PROVISIONER:-team9}
REPO_DIR=${REPO_DIR:-/shared/hackathon-team9}
# fuzzball/setup.fz ingresses the model to the volume root:
MODEL_DIR=${MODEL_DIR:-/shared/nemotron-3-nano-30b-a3b-bf16}
# Every multinode rank sees the same fb0 container bridge address: keep NCCL off lo and fb0.
# Replace with the real NIC name from the setup probe once known.
NCCL_IFACE=${NCCL_IFACE:-^lo,fb0,docker0}
CONFIG_1N=${CONFIG_1N:-configs/single-1n.yaml}
CONFIG_2N=${CONFIG_2N:-configs/ddp-2n.yaml}
GIT_URL=${GIT_URL:-https://github.com/mkchoithani/hackathon-team9.git}
GIT_BRANCH=${GIT_BRANCH:-dev}
COLLECT_TAG=${COLLECT_TAG:-$(date -u +%Y%m%dT%H%M%SZ)}   # names the results tarball in the object cache

mkdir -p rendered
for t in templates/*.fz; do
  sed -e "s#@IMAGE@#${IMAGE}#g" -e "s#@VOLUME@#${VOLUME}#g" -e "s#@PROVISIONER@#${PROVISIONER}#g" \
      -e "s#@REPO_DIR@#${REPO_DIR}#g" -e "s#@MODEL_DIR@#${MODEL_DIR}#g" -e "s#@PORT@#${PORT}#g" \
      -e "s#@CONFIG_1N@#${CONFIG_1N}#g" -e "s#@CONFIG_2N@#${CONFIG_2N}#g" \
      -e "s#@GIT_URL@#${GIT_URL}#g" -e "s#@GIT_BRANCH@#${GIT_BRANCH}#g" \
      -e "s#@COLLECT_TAG@#${COLLECT_TAG}#g" "$t" > "rendered/$(basename "$t")"
done
{
  echo "# generated by fuzzball/render.sh on $(date -u +%FT%TZ)"
  echo "export PORT=${PORT}"
  echo "export NNODES=${NNODES:-2}"
  echo "export MODEL_DIR=${MODEL_DIR}"
  # LOCAL_MODEL_DIR is opt-in only: /tmp is RAM on the GB10 nodes, the full copy OOM-kills the trainer.
  # Slow NFS loads are handled by scripts/fastload (on by default in launch_train.sh).
  [[ -n "${LOCAL_MODEL_DIR:-}" ]] && echo "export LOCAL_MODEL_DIR=${LOCAL_MODEL_DIR}"
  [[ -n "${NCCL_IFACE:-}" ]] && echo "export NCCL_SOCKET_IFNAME=${NCCL_IFACE}"
  [[ -n "${NCCL_IB_HCA:-}" ]] && echo "export NCCL_IB_HCA=${NCCL_IB_HCA}"
  [[ -n "${NCCL_IB_DISABLE:-}" ]] && echo "export NCCL_IB_DISABLE=${NCCL_IB_DISABLE}"
  true
} > cluster.env
grep -l '@[A-Z_0-9]*@' rendered/*.fz && { echo "unfilled placeholders above" >&2; exit 1; } || true
for k in IMAGE VOLUME PROVISIONER PORT NCCL_IFACE NCCL_IB_HCA NCCL_IB_DISABLE NNODES REPO_DIR MODEL_DIR \
         CONFIG_1N CONFIG_2N GIT_URL GIT_BRANCH; do
  if [[ -n "${!k:-}" ]]; then echo "$k=${!k}"; fi
done > render.env
echo "1-node config: ${CONFIG_1N}   2-node config: ${CONFIG_2N}"
echo "Rendered: $(ls rendered/*.fz | tr '\n' ' ')"
echo "cluster.env:"; cat cluster.env
echo "Next: git add fuzzball/cluster.env fuzzball/render.env && git commit && git push; 00_stage_code.fz pulls them onto the volume."
